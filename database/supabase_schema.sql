-- ============================================================================
-- QUALITYCHECK - ESQUEMA DE BASE DE DATOS (SUPABASE / POSTGRESQL)
-- Sistema de Gestión y Evaluación de Calidad de Software (ISO/IEC 25010)
-- ============================================================================

-- Habilitar extensión para generación de UUIDs si se requiere en el futuro
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ============================================================================
-- 0. TABLA: users (Gestionada por project_service / autenticación)
-- Almacena los usuarios registrados y el usuario administrador base.
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(150) UNIQUE,
    password_hash TEXT NOT NULL,
    role VARCHAR(30) NOT NULL DEFAULT 'evaluator'
        CHECK (role IN ('admin', 'evaluator', 'viewer')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================================
-- 1. TABLA: projects (Gestionada por project_service)
-- Almacena la información general de los proyectos de software evaluados.
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    responsible VARCHAR(100) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'Activo'
        CHECK (status IN ('Planificación', 'Activo', 'En Pruebas', 'Completado', 'Pausado')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================================
-- 2. TABLA: requirements (Gestionada por qa_service)
-- Registra los requisitos funcionales y no funcionales asociados a un proyecto.
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
    code VARCHAR(30) NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    req_type VARCHAR(30) NOT NULL DEFAULT 'Funcional'
        CHECK (req_type IN ('Funcional', 'No Funcional')),
    priority VARCHAR(20) NOT NULL DEFAULT 'Media'
        CHECK (priority IN ('Alta', 'Media', 'Baja')),
    status VARCHAR(30) NOT NULL DEFAULT 'Pendiente'
        CHECK (status IN ('Pendiente', 'En Progreso', 'Verificado', 'Rechazado')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (project_id, code)
);

-- ============================================================================
-- 3. TABLA: test_cases (Gestionada por qa_service)
-- Casos de prueba diseñados y vinculados a un requisito específico.
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.test_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
    requirement_id BIGINT NOT NULL REFERENCES public.requirements(id) ON DELETE CASCADE,
    code VARCHAR(30) NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    expected_result TEXT,
    execution_status VARCHAR(25) NOT NULL DEFAULT 'Pendiente'
        CHECK (execution_status IN ('Pendiente', 'Aprobado', 'Fallido', 'Bloqueado')),
    executed_by VARCHAR(100),
    executed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (project_id, code)
);

-- ============================================================================
-- 4. TABLA: defects (Gestionada por qa_service)
-- Defectos o bugs detectados durante la ejecución de los casos de prueba.
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.defects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
    test_case_id BIGINT NOT NULL REFERENCES public.test_cases(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    severity VARCHAR(20) NOT NULL DEFAULT 'Media'
        CHECK (severity IN ('Crítica', 'Alta', 'Media', 'Baja')),
    responsible VARCHAR(100) NOT NULL,
    status VARCHAR(25) NOT NULL DEFAULT 'Abierto'
        CHECK (status IN ('Abierto', 'En Reparación', 'Resuelto', 'Cerrado')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolved_at TIMESTAMPTZ
);

-- ============================================================================
-- 5. TABLA: iso25010_evaluations (Gestionada por metrics_service)
-- Registro de evaluaciones de calidad basadas en el estándar ISO/IEC 25010.
-- Escala de evaluación de 0.00 a 100.00 para cada característica de calidad.
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.iso25010_evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
    evaluator VARCHAR(100) NOT NULL,
    functional_suitability_score NUMERIC(5,2) NOT NULL
        CHECK (functional_suitability_score >= 0 AND functional_suitability_score <= 100),
    performance_efficiency_score NUMERIC(5,2) NOT NULL
        CHECK (performance_efficiency_score >= 0 AND performance_efficiency_score <= 100),
    maintainability_score NUMERIC(5,2) NOT NULL
        CHECK (maintainability_score >= 0 AND maintainability_score <= 100),
    overall_score NUMERIC(5,2) GENERATED ALWAYS AS (
        ROUND((functional_suitability_score + performance_efficiency_score + maintainability_score) / 3.0, 2)
    ) STORED,
    observations TEXT,
    evaluated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================================
-- 6. TABLA: code_audits (Gestionada por metrics_service)
-- Almacena el historial de auditorías estáticas de archivos o carpetas.
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.code_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT REFERENCES public.projects(id) ON DELETE CASCADE,
    source_name VARCHAR(200) NOT NULL,
    total_files INTEGER NOT NULL DEFAULT 0,
    total_lines INTEGER NOT NULL DEFAULT 0,
    code_lines INTEGER NOT NULL DEFAULT 0,
    comment_lines INTEGER NOT NULL DEFAULT 0,
    comment_density NUMERIC(5,2) NOT NULL DEFAULT 0,
    functions_count INTEGER NOT NULL DEFAULT 0,
    classes_count INTEGER NOT NULL DEFAULT 0,
    suggested_maintainability_score NUMERIC(5,2) NOT NULL DEFAULT 0,
    summary_json JSONB,
    audited_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================================
-- ÍNDICES PARA OPTIMIZACIÓN DE CONSULTAS E INDICADORES
-- ============================================================================
CREATE INDEX IF NOT EXISTS idx_requirements_project ON public.requirements(project_id);
CREATE INDEX IF NOT EXISTS idx_test_cases_project ON public.test_cases(project_id);
CREATE INDEX IF NOT EXISTS idx_test_cases_requirement ON public.test_cases(requirement_id);
CREATE INDEX IF NOT EXISTS idx_defects_project ON public.defects(project_id);
CREATE INDEX IF NOT EXISTS idx_defects_test_case ON public.defects(test_case_id);
CREATE INDEX IF NOT EXISTS idx_iso_evaluations_project ON public.iso25010_evaluations(project_id);
CREATE INDEX IF NOT EXISTS idx_code_audits_project ON public.code_audits(project_id);
CREATE INDEX IF NOT EXISTS idx_users_username ON public.users(username);

